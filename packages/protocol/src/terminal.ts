import type { HistoryRow, HistoryStyle } from './history.js';

/**
 * Live terminal channel (terminal protocol v1, carried inside bridge protocol v1).
 *
 * A client opens a stream per terminal it shows. Control messages are JSON text
 * frames like the rest of the protocol; screen bytes are binary frames:
 *
 *   server -> client: `[stream u32 LE][raw VT bytes]`
 *   client -> server: `[stream u32 LE][kind u8][bytes]`, kind = BinaryInputKind
 *
 * Lifecycle of a stream:
 *   term.open -> term.opened, then ONE binary frame with a screen snapshot
 *   (scrollback + screen + modes, ready for a fresh xterm.js), then live bytes.
 *   term.resized: the terminal's grid changed (the desktop resized it); fit or
 *   scale the view, never ask for a size: the phone never resizes terminals.
 *   term.reset: throw away what the stream showed (`terminal.reset()`); the next
 *   binary frame is a fresh snapshot. Sent when the client fell behind (its
 *   backlog was dropped), after the bridge reconnected to herdr-core, or on
 *   `term.resync`.
 *   term.closed: the stream is over (closed, exited, gone, ...).
 *
 * History (v2): `term.opened` / `term.reset` carry a HistoryMark: where the
 * snapshot's screen starts in the bridge's numbering of the terminal's
 * main-buffer rows. Rows above it are paged with `term.history` (a cursor =
 * epoch + absolute row number; `older` pages walk up, `newer` ones fill in rows
 * that scrolled off since) and come back as `term.history.page`. A new epoch
 * (the bridge re-attached, or the width changed and rows re-wrapped) makes old
 * cursors `stale`: start over from the latest mark.
 *
 * Input never changes the terminal's size: the bridge types through a viewer
 * attached at the terminal's current grid.
 */

/** Bumped when a terminal message changes incompatibly; sent in `term.opened`. */
export const TERMINAL_PROTOCOL_VERSION = 2;

/** Version of the history rows format in `term.history.page`. */
export const TERMINAL_HISTORY_VERSION = 1;

/** Kind byte of a client binary frame. */
export const BinaryInputKind = {
  /** Keyboard or paste bytes from the person (xterm.js `onData`). */
  KEYS: 0,
  /** Replies the client's terminal emulator generated by itself (DA, DSR, ...). herdr-core already answers these; the bridge drops them. */
  AUTOMATIC: 1,
} as const;
export type BinaryInputKind = (typeof BinaryInputKind)[keyof typeof BinaryInputKind];

/** Size limits the bridge enforces (bigger input is refused with `too_large`). */
export const TERMINAL_LIMITS = {
  /** Bytes of one binary input frame (after the 5-byte header). */
  maxInputBytes: 64 * 1024,
  /** Characters of one `term.send`. */
  maxSendChars: 64 * 1024,
  /** Keys in one `term.keys`. */
  maxKeys: 32,
  /** Keys in one `term.answer` (arrows across a question's options, then Enter). */
  maxAnswerKeys: 12,
  /** Scrollback lines a snapshot can carry. */
  maxHistory: 2000,
  /** Rows of one `term.history` page. */
  maxHistoryPage: 1000,
  /** Lines of a full-screen app's history one `term.appHistory` reads (herdr-core's own cap). */
  maxAppHistory: 1000,
} as const;

/** A place in a terminal's main-buffer history: `line` counts rows since the bridge's record began (`epoch`). */
export interface HistoryCursor {
  epoch: number;
  line: number;
}

/** Where a snapshot sits in the history (in `term.opened` / `term.reset`). */
export interface HistoryMark {
  epoch: number;
  /** The absolute number of the snapshot's first screen row of the main buffer: history rows are the ones before it. */
  end: number;
  /** History rows the bridge holds before `end`. */
  kept: number;
  /** The program is on the alternate screen (a full-screen app): its own history is inside the app, not here. */
  alt: boolean;
}

// ---- client -> server ----

export interface TermOpen {
  t: 'term.open';
  /** Client-chosen request id, echoed in `term.opened` / `term.error`. */
  req: number;
  terminalId: string;
  /** Lines of scrollback in the first snapshot (default 1000, at most TERMINAL_LIMITS.maxHistory). */
  history?: number;
}

export interface TermClose {
  t: 'term.close';
  stream: number;
}

/** Ask for a fresh snapshot (answered with `term.reset` + a snapshot frame). */
export interface TermResync {
  t: 'term.resync';
  stream: number;
}

/**
 * Press named keys: enter, esc, tab, shift+tab, backspace, delete, space, up,
 * down, left, right, home, end, pageup, pagedown, ctrl+a..ctrl+z, and single
 * printable characters ("y", "n", "1", "/"). Encoded for the terminal's
 * current cursor-key mode and typed at once (no quiet period).
 */
export interface TermKeys {
  t: 'term.keys';
  /** Optional request id: when set, success is acknowledged with `term.ack`. */
  req?: number;
  /** Idempotency key (1-64 chars, unique per input): a retry with the same id is acknowledged, never typed twice. */
  id?: string;
  terminalId: string;
  keys: string[];
}

/**
 * Chat-style send: paste `text` (bracketed when the program asked), then
 * Enter, typed by the bridge; refused for a blocked program unless `force`.
 */
export interface TermSend {
  t: 'term.send';
  req?: number;
  /** Idempotency key: send it again with the same id after a reconnect; it is typed at most once. */
  id?: string;
  /** false: paste only, no Enter ("type without Enter"). Default true. */
  enter?: boolean;
  terminalId: string;
  text: string;
  /** Type even when the program is blocked (answering its prompt). */
  force?: boolean;
}

/**
 * Quick approve/deny for a blocked agent: the client says which keys answer
 * the prompt ("1", "y", "enter", "esc", ...). The bridge only types them when
 * the agent is blocked right now (and, with `turn`, still on that turn), and
 * only short answers from TERMINAL_ANSWER_KEYS.
 */
export interface TermAnswer {
  t: 'term.answer';
  req?: number;
  /** Idempotency key, as for `term.send`. */
  id?: string;
  terminalId: string;
  keys: string[];
  /** The turn the client saw the prompt on; refused as `stale` if it moved on. */
  turn?: number;
}

/** Keys `term.answer` accepts. */
export const TERMINAL_ANSWER_KEYS: readonly string[] = [
  '1',
  '2',
  '3',
  '4',
  '5',
  '6',
  '7',
  '8',
  '9',
  'y',
  'n',
  'a',
  'enter',
  'esc',
  'tab',
  'shift+tab',
  'up',
  'down',
  'left',
  'right',
  'space',
  // Clears the "Type something" field before a typed answer goes in.
  'ctrl+u',
];

/** A page of main-buffer history (read only). Answered with `term.history.page`, or `term.error` (`stale`: the cursor's epoch is over). */
export interface TermHistory {
  t: 'term.history';
  req: number;
  stream: number;
  cursor: HistoryCursor;
  /** `older`: up to `limit` rows just before `cursor.line`; `newer`: rows from `cursor.line` on. */
  dir: 'older' | 'newer';
  /** Rows (default 300, at most TERMINAL_LIMITS.maxHistoryPage). */
  limit?: number;
}

/**
 * A full-screen app's own earlier output, read the way `hc read --lines` does: herdr-core scrolls the app up with
 * the mouse wheel, reads each page and scrolls it back (live output pauses for those seconds; keys typed meanwhile
 * wait). Plain text. Only on request, only while the stream shows the alternate screen; herdr-core refuses (and
 * answers with the screen alone) while the program is working, blocked or in error.
 */
export interface TermAppHistory {
  t: 'term.appHistory';
  req: number;
  stream: number;
  /** Lines (default and most: TERMINAL_LIMITS.maxAppHistory). */
  lines?: number;
}

export type TerminalClientMessage = TermOpen | TermClose | TermResync | TermKeys | TermSend | TermAnswer | TermHistory | TermAppHistory;

// ---- server -> client ----

export interface TermOpened {
  t: 'term.opened';
  req: number;
  /** Binary frames of this stream carry this id. */
  stream: number;
  terminalId: string;
  /** The terminal's grid now (the desktop's size). */
  cols: number;
  rows: number;
  /** TERMINAL_PROTOCOL_VERSION. */
  v: number;
  /** Where the snapshot that follows sits in the history (v2). */
  history?: HistoryMark;
}

export interface TermResized {
  t: 'term.resized';
  stream: number;
  cols: number;
  rows: number;
}

export interface TermReset {
  t: 'term.reset';
  stream: number;
  cols: number;
  rows: number;
  reason: 'behind' | 'reconnect' | 'resync';
  history?: HistoryMark;
}

/** Rows `[start, start + rows.length)` of the main-buffer history. */
export interface TermHistoryPage {
  t: 'term.history.page';
  req: number;
  stream: number;
  /** TERMINAL_HISTORY_VERSION. */
  v: number;
  epoch: number;
  start: number;
  rows: HistoryRow[];
  styles: HistoryStyle[];
  /** Rows the bridge still holds before `start`. */
  older: number;
  /** The history's end now (the first screen row). */
  end: number;
  /**
   * Why nothing older is held (when `older` is 0): `start`, everything herdr-core held when the bridge attached
   * (herdr-core keeps ~5 MB of rows per terminal); `trimmed`, the bridge's own cap dropped older rows.
   */
  edge?: 'start' | 'trimmed';
}

export interface TermClosed {
  t: 'term.closed';
  stream: number;
  /** `closed` (asked), `exited`, `killed`, ... (herdr-core's reason), `gone`, `unavailable`. */
  reason: string;
}

/** A request with a `req` succeeded. */
export interface TermAck {
  t: 'term.ack';
  req: number;
}

export type TermErrorCode =
  | 'not_found'
  | 'bad_request'
  | 'bad_key'
  | 'too_large'
  | 'rate_limited'
  | 'not_blocked'
  | 'stale'
  | 'unavailable'
  | 'core_error';

export interface TermError {
  t: 'term.error';
  /** The failed request's id, when it had one. */
  req?: number;
  stream?: number;
  terminalId?: string;
  code: TermErrorCode;
  message: string;
}

/** The answer to `term.appHistory`: the lines above the app's current screen, oldest first. */
export interface TermAppHistoryResult {
  t: 'term.appHistory.result';
  req: number;
  stream: number;
  lines: string[];
  /** It reached the top of the app's history. */
  complete: boolean;
  /** Why nothing could be read (herdr-core's status word: working, blocked, error), when it couldn't. */
  why?: string;
}

export type TerminalServerMessage =
  | TermOpened
  | TermResized
  | TermReset
  | TermClosed
  | TermAck
  | TermError
  | TermHistoryPage
  | TermAppHistoryResult;

// ---- binary helpers (work on Uint8Array in browsers and Buffers in Node) ----

/** Header of a server binary frame: the stream id. */
export const SERVER_BINARY_HEADER = 4;
/** Header of a client binary frame: stream id + kind. */
export const CLIENT_BINARY_HEADER = 5;

/** Builds a client input frame. */
export function encodeInputFrame(stream: number, data: Uint8Array, kind: BinaryInputKind = BinaryInputKind.KEYS): Uint8Array {
  const out = new Uint8Array(CLIENT_BINARY_HEADER + data.length);
  new DataView(out.buffer).setUint32(0, stream, true);
  out[4] = kind;
  out.set(data, CLIENT_BINARY_HEADER);
  return out;
}

/** Reads a client input frame; null when it is too short. */
export function decodeInputFrame(frame: Uint8Array): { stream: number; kind: number; data: Uint8Array } | null {
  if (frame.length < CLIENT_BINARY_HEADER) return null;
  const view = new DataView(frame.buffer, frame.byteOffset, frame.byteLength);
  return { stream: view.getUint32(0, true), kind: frame[4] ?? 0, data: frame.subarray(CLIENT_BINARY_HEADER) };
}

/** Reads a server output frame; null when it is too short. */
export function decodeOutputFrame(frame: Uint8Array): { stream: number; data: Uint8Array } | null {
  if (frame.length < SERVER_BINARY_HEADER) return null;
  const view = new DataView(frame.buffer, frame.byteOffset, frame.byteLength);
  return { stream: view.getUint32(0, true), data: frame.subarray(SERVER_BINARY_HEADER) };
}
